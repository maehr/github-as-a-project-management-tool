"""Render the course data files into Markdown pages.

Inputs:  course/schedule.yml, project-management/backlog.yml
Outputs: course/_schedule.md (included by course/syllabus.qmd),
         course/exercises/_x2-texts.md (included by course/exercises/x2.qmd)

The outputs are committed. A test fails when they are stale.
Run with ``npm run pages:render``.

The full example backlog has no page on the site. The showcase Project shows
it, and src/seed_backlog.py writes it to GitHub. The site shows only the
Issue texts that learners copy in X2.
"""

from __future__ import annotations

from pathlib import Path

from backlog import ROOT, Backlog, issue_body, issue_title, load_backlog, load_schedule

GENERATED = (
    "<!-- Generated by src/render_pages.py from {source}. "
    "Do not edit by hand. Run `npm run pages:render`. -->"
)


def cell(value: object) -> str:
    return str(value).replace("|", "\\|")


def render_schedule(schedule: dict) -> str:
    out = [
        GENERATED.format(source="course/schedule.yml"),
        "",
        "| Time | Activity | Learner evidence |",
        "| --- | --- | --- |",
    ]
    for block in schedule["blocks"]:
        if block["kind"] == "exercise":
            label = (
                f"**[{block['id']}](exercises/{block['id'].lower()}.qmd)** "
                f"{block['title']}"
            )
        elif block["kind"] == "break":
            label = "_Break_"
        else:
            label = block["title"]
        evidence = block.get("evidence", "—")
        out.append(f"| {block['start']}–{block['end']} | {label} | {cell(evidence)} |")
    out.append("")
    return "\n".join(out)


def render_x2_texts(backlog: Backlog) -> str:
    """Titles and bodies of the Issues that learners copy in X2.

    E01-T1 is missing on purpose: learners write it themselves.
    """
    out: list[str] = [GENERATED.format(source="project-management/backlog.yml")]
    for item in backlog.items:
        if not item.get("learner") or item["id"] == "E01-T1":
            continue
        out += [
            "",
            f"### {item['id']} {{#text-{item['id'].lower()}}}",
            "",
            f"Title: `{issue_title(item)}` · Label: `kind:{item['kind']}`",
            "",
            "```markdown",
            issue_body(item, backlog),
            "```",
        ]
    out.append("")
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    return {
        ROOT / "course" / "_schedule.md": render_schedule(load_schedule()),
        ROOT / "course" / "exercises" / "_x2-texts.md": render_x2_texts(load_backlog()),
    }


def main() -> None:
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
