"""Render the course data files into Markdown pages.

Inputs:  project-management/backlog.yml, project-management/milestones.yml,
         course/schedule.yml
Outputs: project-management/backlog.md, project-management/milestones.md,
         course/_schedule.md (included by course/syllabus.qmd)

The outputs are committed. A test fails when they are stale.
Run with ``npm run pages:render``.
"""

from __future__ import annotations

from pathlib import Path

from backlog import (
    ROOT,
    Backlog,
    basis_line,
    issue_body,
    issue_title,
    load_backlog,
    load_milestones,
    load_schedule,
)

GENERATED = (
    "<!-- Generated by src/render_pages.py from {source}. "
    "Do not edit by hand. Run `npm run pages:render`. -->"
)


def cell(value: object) -> str:
    return str(value).replace("|", "\\|")


def render_backlog(backlog: Backlog, milestones: list[dict]) -> str:
    titles = {m["id"]: m["title"] for m in milestones}
    out = [
        "---",
        "title: Example backlog",
        "description: Full example backlog for the fictional master's thesis, E01 to E08.",
        "---",
        "",
        GENERATED.format(source="project-management/backlog.yml"),
        "",
        "This page shows the instructor's full example backlog for the fictional thesis. "
        "The source is [`backlog.yml`](backlog.yml). "
        "Learners build only **E01** and **E08** by hand. "
        "The other epics show how the plan continues.",
        "",
        "::: {.callout-important}",
        "All people, dates, and records are fictional. The dates are planning "
        "estimates. Rule items cite the regulation that applies to the MA Digital "
        "Humanities (Major). A student in another programme must use the rules of "
        "that programme.",
        ":::",
        "",
        "## Epics",
        "",
        "| Epic | Outcome | Sub-issues | Planned | Learner |",
        "| --- | --- | --- | --- | --- |",
    ]
    for epic in backlog.epics():
        start, target = backlog.epic_dates(epic["id"])
        learner = "yes" if epic.get("learner") else "no"
        out.append(
            f"| [{epic['id']}](#{epic['id'].lower()}) {cell(epic['title'])} "
            f"| {cell(epic['outcome'])} | {len(backlog.children(epic['id']))} "
            f"| {start} to {target} | {learner} |"
        )
    for epic in backlog.epics():
        out += [
            "",
            f"## {epic['id']} {epic['title']} {{#{epic['id'].lower()}}}",
            "",
            epic["outcome"],
            "",
            "| ID | Kind | Title | Basis | Milestone | Planned | Blocked by |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for kid in backlog.children(epic["id"]):
            milestone = kid.get("milestone")
            milestone_text = f"{milestone} {titles[milestone]}" if milestone else ""
            marker = " (learner)" if kid.get("learner") else ""
            out.append(
                f"| {kid['id']}{marker} | `kind:{kid['kind']}` | {cell(kid['title'])} "
                f"| {cell(basis_line(kid, backlog.sources))} | {cell(milestone_text)} "
                f"| {kid['start']} to {kid['target']} "
                f"| {', '.join(kid.get('blocked_by', []))} |"
            )
        for kid in backlog.children(epic["id"]):
            out += [
                "",
                f'::: {{.callout-note collapse="true" '
                f'title="{kid["id"]}: Issue title and body"}}',
                "",
                f"**Title:** `{issue_title(kid)}`",
                "",
                "```markdown",
                issue_body(kid, backlog),
                "```",
                "",
                ":::",
            ]
    out += [
        "",
        "## Sources",
        "",
        "| ID | Document | Applies to |",
        "| --- | --- | --- |",
    ]
    for source_id, source in backlog.sources.items():
        out.append(
            f"| {source_id} | [{cell(source['title'].strip())}]({source['url']}) "
            f"| {cell(source['applicability'])} |"
        )
    out += [
        "",
        f"Sources retrieved on {backlog.meta['retrieved']}.",
        "",
    ]
    return "\n".join(out)


def render_milestones(milestones: list[dict]) -> str:
    out = [
        "---",
        "title: Milestones",
        "description: Milestones of the fictional master's thesis with justified dates.",
        "---",
        "",
        GENERATED.format(source="project-management/milestones.yml"),
        "",
        "The source is [`milestones.yml`](milestones.yml). "
        "A **fictional-formal** date stands in for an official date that the "
        "Dean's Office sets. A **proposed** date is a planning estimate.",
        "",
        "::: {.callout-warning}",
        "Never move a fictional-formal date silently. Adjust the planned work, and "
        "record the decision.",
        ":::",
        "",
        "| ID | Title | Due | Date status | Contents |",
        "| --- | --- | --- | --- | --- |",
    ]
    for m in milestones:
        out.append(
            f"| {m['id']} | {cell(m['title'])} | {m['due']} | {m['date_status']} "
            f"| {cell(m['description'].strip())} |"
        )
    for m in milestones:
        out += [
            "",
            f"## {m['id']} {m['title']}",
            "",
            f"**Due:** {m['due']} ({m['date_status']})",
            "",
            f"**Justification:** {m['justification'].strip()}",
        ]
    out.append("")
    return "\n".join(out)


def render_schedule(schedule: dict) -> str:
    out = [
        GENERATED.format(source="course/schedule.yml"),
        "",
        "| Time | Activity | Learner evidence |",
        "| --- | --- | --- |",
    ]
    for block in schedule["blocks"]:
        if block["kind"] == "exercise":
            label = (
                f"**[{block['id']}](exercises/{block['id'].lower()}.qmd)** "
                f"{block['title']}"
            )
        elif block["kind"] == "break":
            label = "_Break_"
        else:
            label = block["title"]
        evidence = block.get("evidence", "—")
        out.append(f"| {block['start']}–{block['end']} | {label} | {cell(evidence)} |")
    out.append("")
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    backlog = load_backlog()
    milestones = load_milestones()
    return {
        ROOT / "project-management" / "backlog.md": render_backlog(backlog, milestones),
        ROOT / "project-management" / "milestones.md": render_milestones(milestones),
        ROOT / "course" / "_schedule.md": render_schedule(load_schedule()),
    }


def main() -> None:
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
